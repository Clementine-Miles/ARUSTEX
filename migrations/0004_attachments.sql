-- ARUSTEX schema, part 4: content-addressed attachment storage in PostgreSQL.

CREATE TABLE blobs (
    hash        TEXT PRIMARY KEY CHECK (hash ~ '^[0-9a-f]{64}$'),
    size        BIGINT NOT NULL CHECK (size >= 0),
    chunk_size  INTEGER NOT NULL CHECK (chunk_size BETWEEN 4096 AND 1048576),
    chunk_count INTEGER NOT NULL CHECK (chunk_count >= 0),
    -- false while chunks are still being written; incomplete blobs are never served.
    complete    BOOLEAN NOT NULL DEFAULT false,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE blob_chunks (
    blob_hash  TEXT NOT NULL REFERENCES blobs(hash) ON DELETE CASCADE,
    idx        INTEGER NOT NULL CHECK (idx >= 0),
    data       BYTEA NOT NULL CHECK (octet_length(data) BETWEEN 1 AND 1048576),
    chunk_hash TEXT NOT NULL CHECK (chunk_hash ~ '^[0-9a-f]{64}$'),
    PRIMARY KEY (blob_hash, idx)
);

CREATE TABLE attachments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner           TEXT NOT NULL CHECK (owner IN ('task', 'record', 'finding', 'report')),
    owner_id        BIGINT NOT NULL,
    name            TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 255),
    media_type      TEXT NOT NULL,
    blob_hash       TEXT NOT NULL REFERENCES blobs(hash) ON DELETE RESTRICT,
    size            BIGINT NOT NULL CHECK (size >= 0),
    retention_until TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_attachments_owner ON attachments (owner, owner_id);
CREATE INDEX idx_attachments_blob ON attachments (blob_hash);
