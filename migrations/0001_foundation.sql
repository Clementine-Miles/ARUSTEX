-- ARUSTEX schema, part 1: tasks, graphs, assets, datasets, records, findings, events.
-- Migrations are versioned and applied by `arustex db migrate`; never edit an applied file.

CREATE FUNCTION arustex_touch_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

-- ---------------------------------------------------------------------------
-- Exploration graphs (one per task)
-- ---------------------------------------------------------------------------
CREATE TABLE explorations (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    objective  TEXT NOT NULL,
    status     TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'achieved', 'failed')),
    round      BIGINT NOT NULL DEFAULT 0 CHECK (round >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TRIGGER trg_explorations_touch BEFORE UPDATE ON explorations
    FOR EACH ROW EXECUTE FUNCTION arustex_touch_updated_at();

-- ---------------------------------------------------------------------------
-- Datasets and imported records
-- ---------------------------------------------------------------------------
CREATE TABLE datasets (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           TEXT NOT NULL UNIQUE CHECK (length(name) BETWEEN 1 AND 200),
    description    TEXT NOT NULL DEFAULT '',
    source         TEXT NOT NULL,
    retention_days INTEGER NOT NULL DEFAULT 0 CHECK (retention_days >= 0),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE records (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id      BIGINT NOT NULL REFERENCES datasets(id) ON DELETE CASCADE,
    external_id     TEXT NOT NULL CHECK (length(external_id) BETWEEN 1 AND 256),
    title           TEXT NOT NULL DEFAULT '',
    content_type    TEXT NOT NULL CHECK (content_type IN
                        ('text/plain', 'text/markdown', 'application/json', 'text/csv')),
    body            TEXT NOT NULL DEFAULT '',
    fields          JSONB NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(fields) = 'object'),
    content_hash    TEXT NOT NULL CHECK (content_hash ~ '^[0-9a-f]{64}$'),
    redacted        BOOLEAN NOT NULL DEFAULT false,
    origin          TEXT NOT NULL DEFAULT 'supplied',
    source          TEXT NOT NULL,
    locator         TEXT,
    imported_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    retention_until TIMESTAMPTZ,
    search          TSVECTOR GENERATED ALWAYS AS (
                        to_tsvector('simple', title || ' ' || external_id || ' ' || body)
                    ) STORED,
    UNIQUE (dataset_id, external_id)
);
CREATE INDEX idx_records_search ON records USING GIN (search);
CREATE INDEX idx_records_dataset ON records (dataset_id, id);
CREATE INDEX idx_records_retention ON records (retention_until) WHERE retention_until IS NOT NULL;

-- ---------------------------------------------------------------------------
-- Tasks
-- ---------------------------------------------------------------------------
CREATE TABLE tasks (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            TEXT NOT NULL DEFAULT '',
    objective       TEXT NOT NULL CHECK (length(objective) > 0),
    description     TEXT NOT NULL DEFAULT '',
    status          TEXT NOT NULL DEFAULT 'created' CHECK (status IN (
                        'created', 'queued', 'running', 'paused', 'needs_review',
                        'completed', 'failed', 'cancelled', 'timed_out')),
    exploration_id  BIGINT NOT NULL UNIQUE REFERENCES explorations(id) ON DELETE RESTRICT,
    batch_size      INTEGER NOT NULL DEFAULT 25 CHECK (batch_size BETWEEN 1 AND 1000),
    max_workers     INTEGER NOT NULL DEFAULT 2 CHECK (max_workers BETWEEN 1 AND 64),
    timeout_seconds INTEGER NOT NULL DEFAULT 0 CHECK (timeout_seconds >= 0),
    token_budget    BIGINT NOT NULL DEFAULT 0 CHECK (token_budget >= 0),
    tokens_used     BIGINT NOT NULL DEFAULT 0 CHECK (tokens_used >= 0),
    legacy_id       BIGINT UNIQUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at      TIMESTAMPTZ,
    completed_at    TIMESTAMPTZ
);
CREATE INDEX idx_tasks_status ON tasks (status, id);
CREATE TRIGGER trg_tasks_touch BEFORE UPDATE ON tasks
    FOR EACH ROW EXECUTE FUNCTION arustex_touch_updated_at();

CREATE TABLE task_datasets (
    task_id    BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    dataset_id BIGINT NOT NULL REFERENCES datasets(id) ON DELETE RESTRICT,
    PRIMARY KEY (task_id, dataset_id)
);
CREATE INDEX idx_task_datasets_dataset ON task_datasets (dataset_id);

-- ---------------------------------------------------------------------------
-- Exploration nodes and edges (legacy kinds, states and relations preserved)
-- ---------------------------------------------------------------------------
CREATE TABLE exploration_nodes (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exploration_id BIGINT NOT NULL REFERENCES explorations(id) ON DELETE CASCADE,
    kind           TEXT NOT NULL,
    state          TEXT NOT NULL,
    priority       INTEGER NOT NULL DEFAULT 0,
    title          TEXT NOT NULL DEFAULT '',
    payload        JSONB NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(payload) = 'object'),
    origin         TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at   TIMESTAMPTZ,
    CONSTRAINT ck_node_kind CHECK (kind IN ('begin', 'goal', 'intent', 'fact', 'finding', 'hint', 'digest')),
    CONSTRAINT ck_node_state CHECK (
        (kind = 'begin'   AND state IN ('open')) OR
        (kind = 'intent'  AND state IN ('open', 'running', 'paused', 'done', 'blocked', 'exhausted', 'stopped', 'deleted')) OR
        (kind = 'goal'    AND state IN ('open', 'met', 'abandoned')) OR
        (kind = 'fact'    AND state IN ('confirmed', 'dismissed', 'origin')) OR
        (kind = 'finding' AND state IN ('confirmed', 'dismissed')) OR
        (kind = 'hint'    AND state IN ('active', 'consumed')) OR
        (kind = 'digest'  AND state IN ('active', 'superseded'))
    )
);
CREATE INDEX idx_nodes_exploration ON exploration_nodes (exploration_id, kind);
CREATE UNIQUE INDEX uq_nodes_one_begin ON exploration_nodes (exploration_id) WHERE kind = 'begin';
CREATE TRIGGER trg_nodes_touch BEFORE UPDATE ON exploration_nodes
    FOR EACH ROW EXECUTE FUNCTION arustex_touch_updated_at();

CREATE TABLE exploration_edges (
    exploration_id BIGINT NOT NULL REFERENCES explorations(id) ON DELETE CASCADE,
    src_id         BIGINT NOT NULL REFERENCES exploration_nodes(id) ON DELETE CASCADE,
    dst_id         BIGINT NOT NULL REFERENCES exploration_nodes(id) ON DELETE CASCADE,
    rel            TEXT NOT NULL CHECK (rel IN ('spawns', 'derived_from', 'yields', 'proves', 'covers')),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (exploration_id, src_id, rel, dst_id),
    CHECK (src_id <> dst_id)
);
CREATE INDEX idx_edges_src ON exploration_edges (src_id, rel);
CREATE INDEX idx_edges_dst ON exploration_edges (dst_id, rel);
CREATE UNIQUE INDEX uq_edges_one_spawn_parent ON exploration_edges (dst_id) WHERE rel = 'spawns';

-- Both endpoints of an edge must belong to the edge's exploration.
CREATE FUNCTION arustex_check_edge_exploration() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF (SELECT count(*) FROM exploration_nodes
        WHERE id IN (NEW.src_id, NEW.dst_id) AND exploration_id = NEW.exploration_id) <> 2 THEN
        RAISE EXCEPTION 'edge endpoints must belong to exploration %', NEW.exploration_id
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_edges_same_exploration BEFORE INSERT OR UPDATE ON exploration_edges
    FOR EACH ROW EXECUTE FUNCTION arustex_check_edge_exploration();

-- ---------------------------------------------------------------------------
-- Global Asset Graph
-- ---------------------------------------------------------------------------
CREATE TABLE assets (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind         TEXT NOT NULL CHECK (kind IN
                     ('organization', 'collection', 'document', 'dataset', 'entity', 'reference')),
    identity_key TEXT NOT NULL CHECK (length(identity_key) BETWEEN 1 AND 1024),
    label        TEXT NOT NULL CHECK (length(label) BETWEEN 1 AND 1024),
    attributes   JSONB NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(attributes) = 'object'),
    origin       TEXT NOT NULL,
    source       TEXT NOT NULL,
    locator      TEXT,
    legacy_id    BIGINT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (kind, identity_key)
);
CREATE INDEX idx_assets_label ON assets (lower(label));
CREATE TRIGGER trg_assets_touch BEFORE UPDATE ON assets
    FOR EACH ROW EXECUTE FUNCTION arustex_touch_updated_at();

CREATE TABLE asset_edges (
    src_id     BIGINT NOT NULL REFERENCES assets(id) ON DELETE CASCADE,
    dst_id     BIGINT NOT NULL REFERENCES assets(id) ON DELETE CASCADE,
    rel        TEXT NOT NULL CHECK (rel IN ('contains', 'references', 'derived_from', 'duplicate_of')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (src_id, rel, dst_id),
    CHECK (src_id <> dst_id)
);
CREATE INDEX idx_asset_edges_dst ON asset_edges (dst_id, rel);
-- Containment is a forest: at most one parent per asset.
CREATE UNIQUE INDEX uq_asset_edges_one_parent ON asset_edges (dst_id) WHERE rel = 'contains';

CREATE TABLE node_record_anchors (
    node_id   BIGINT NOT NULL REFERENCES exploration_nodes(id) ON DELETE CASCADE,
    record_id BIGINT NOT NULL REFERENCES records(id) ON DELETE CASCADE,
    PRIMARY KEY (node_id, record_id)
);
CREATE INDEX idx_node_record_anchors_record ON node_record_anchors (record_id);

CREATE TABLE node_asset_anchors (
    node_id  BIGINT NOT NULL REFERENCES exploration_nodes(id) ON DELETE CASCADE,
    asset_id BIGINT NOT NULL REFERENCES assets(id) ON DELETE CASCADE,
    PRIMARY KEY (node_id, asset_id)
);
CREATE INDEX idx_node_asset_anchors_asset ON node_asset_anchors (asset_id);

-- ---------------------------------------------------------------------------
-- Findings and review notes
-- ---------------------------------------------------------------------------
CREATE TABLE findings (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id    BIGINT REFERENCES tasks(id) ON DELETE SET NULL,
    node_id    BIGINT REFERENCES exploration_nodes(id) ON DELETE SET NULL,
    title      TEXT NOT NULL CHECK (length(title) BETWEEN 1 AND 512),
    category   TEXT NOT NULL DEFAULT '',
    severity   TEXT NOT NULL CHECK (severity IN ('info', 'low', 'medium', 'high', 'critical')),
    status     TEXT NOT NULL DEFAULT 'pending'
                   CHECK (status IN ('pending', 'confirmed', 'dismissed', 'resolved', 'duplicate')),
    summary    TEXT NOT NULL DEFAULT '' CHECK (length(summary) <= 16384),
    origin     TEXT NOT NULL CHECK (origin IN ('supplied', 'model_generated', 'operator', 'derived')),
    source     TEXT NOT NULL,
    locator    TEXT,
    session_id UUID,
    legacy_id  BIGINT UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_findings_task ON findings (task_id, id DESC);
CREATE INDEX idx_findings_status ON findings (status, id DESC);
CREATE TRIGGER trg_findings_touch BEFORE UPDATE ON findings
    FOR EACH ROW EXECUTE FUNCTION arustex_touch_updated_at();

CREATE TABLE finding_records (
    finding_id BIGINT NOT NULL REFERENCES findings(id) ON DELETE CASCADE,
    record_id  BIGINT NOT NULL REFERENCES records(id) ON DELETE CASCADE,
    PRIMARY KEY (finding_id, record_id)
);
CREATE INDEX idx_finding_records_record ON finding_records (record_id);

CREATE TABLE finding_assets (
    finding_id BIGINT NOT NULL REFERENCES findings(id) ON DELETE CASCADE,
    asset_id   BIGINT NOT NULL REFERENCES assets(id) ON DELETE CASCADE,
    PRIMARY KEY (finding_id, asset_id)
);

CREATE TABLE review_notes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject    TEXT NOT NULL CHECK (subject IN ('task', 'finding', 'record', 'review_result')),
    subject_id BIGINT NOT NULL,
    author     TEXT NOT NULL,
    body       TEXT NOT NULL CHECK (length(body) BETWEEN 1 AND 32768),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_review_notes_subject ON review_notes (subject, subject_id, id);

-- ---------------------------------------------------------------------------
-- Durable ordered events and audit log
-- ---------------------------------------------------------------------------
-- Writers take a transaction-scoped advisory lock before inserting, so sequence order
-- equals commit order and subscribers resuming "after seq" never skip an event.
CREATE TABLE events (
    seq        BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    at         TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    kind       TEXT NOT NULL,
    task_id    BIGINT,
    session_id UUID,
    payload    JSONB NOT NULL
);
CREATE INDEX idx_events_task ON events (task_id, seq) WHERE task_id IS NOT NULL;

CREATE TABLE audit_log (
    id      BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    actor   TEXT NOT NULL,
    action  TEXT NOT NULL,
    subject TEXT NOT NULL,
    detail  JSONB NOT NULL DEFAULT '{}'
);
CREATE INDEX idx_audit_log_at ON audit_log (at DESC);
