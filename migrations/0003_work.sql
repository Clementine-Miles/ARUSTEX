-- ARUSTEX schema, part 3: work items (scheduler), approvals, review results, triggers.

CREATE TABLE work_items (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id          BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    kind             TEXT NOT NULL CHECK (kind IN ('review', 'compare')),
    record_ids       BIGINT[] NOT NULL DEFAULT '{}',
    status           TEXT NOT NULL DEFAULT 'queued'
                         CHECK (status IN ('queued', 'leased', 'done', 'failed', 'cancelled')),
    priority         INTEGER NOT NULL DEFAULT 0,
    attempts         INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    max_attempts     INTEGER NOT NULL DEFAULT 3 CHECK (max_attempts >= 1),
    lease_owner      TEXT,
    lease_expires_at TIMESTAMPTZ,
    operation_id     UUID NOT NULL UNIQUE,
    node_id          BIGINT REFERENCES exploration_nodes(id) ON DELETE SET NULL,
    session_id       UUID,
    result           JSONB,
    last_error       TEXT,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK ((status = 'leased') = (lease_owner IS NOT NULL AND lease_expires_at IS NOT NULL)),
    CHECK (cardinality(record_ids) <= 1000)
);
CREATE INDEX idx_work_items_claim ON work_items (priority DESC, id) WHERE status = 'queued';
CREATE INDEX idx_work_items_lease ON work_items (lease_expires_at) WHERE status = 'leased';
CREATE INDEX idx_work_items_task ON work_items (task_id, status);
CREATE TRIGGER trg_work_items_touch BEFORE UPDATE ON work_items
    FOR EACH ROW EXECUTE FUNCTION arustex_touch_updated_at();

ALTER TABLE sessions ADD CONSTRAINT fk_sessions_work_item
    FOREIGN KEY (work_item_id) REFERENCES work_items(id) ON DELETE SET NULL;

CREATE TABLE approvals (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id    BIGINT REFERENCES tasks(id) ON DELETE CASCADE,
    session_id UUID REFERENCES sessions(id) ON DELETE SET NULL,
    operation  TEXT NOT NULL,
    summary    TEXT NOT NULL CHECK (length(summary) <= 4096),
    request    JSONB NOT NULL,
    status     TEXT NOT NULL DEFAULT 'pending'
                   CHECK (status IN ('pending', 'approved', 'rejected', 'applied', 'failed')),
    decided_by TEXT,
    reason     TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    decided_at TIMESTAMPTZ,
    CHECK ((status = 'pending') = (decided_at IS NULL))
);
CREATE INDEX idx_approvals_status ON approvals (status, id DESC);

CREATE TABLE review_results (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id      BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    work_item_id BIGINT REFERENCES work_items(id) ON DELETE SET NULL,
    verdict      TEXT NOT NULL CHECK (verdict IN ('match', 'mismatch', 'inconclusive')),
    details      JSONB NOT NULL DEFAULT '{}',
    status       TEXT NOT NULL DEFAULT 'pending_confirmation'
                     CHECK (status IN ('pending_confirmation', 'confirmed', 'rejected')),
    decided_by   TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    decided_at   TIMESTAMPTZ
);
CREATE INDEX idx_review_results_task ON review_results (task_id, id DESC);
CREATE UNIQUE INDEX uq_review_results_work_item ON review_results (work_item_id) WHERE work_item_id IS NOT NULL;

-- Operator-configured triggers re-queue local processing for an existing task only.
CREATE TABLE triggers (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id          BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    kind             TEXT NOT NULL CHECK (kind IN ('interval', 'event')),
    interval_seconds INTEGER,
    event_kind       TEXT,
    enabled          BOOLEAN NOT NULL DEFAULT true,
    last_fired_at    TIMESTAMPTZ,
    last_event_seq   BIGINT NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (
        (kind = 'interval' AND interval_seconds >= 60 AND event_kind IS NULL) OR
        (kind = 'event' AND interval_seconds IS NULL AND event_kind IN ('records_imported'))
    )
);
