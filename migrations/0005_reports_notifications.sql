-- ARUSTEX schema, part 5: reports and the notification outbox.

CREATE TABLE reports (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id       BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    title         TEXT NOT NULL CHECK (length(title) BETWEEN 1 AND 512),
    status        TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'final')),
    origin        TEXT NOT NULL CHECK (origin IN ('supplied', 'model_generated', 'operator', 'derived')),
    session_id    UUID,
    body_markdown TEXT NOT NULL CHECK (length(body_markdown) <= 4194304),
    document      JSONB NOT NULL DEFAULT '{}',
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    finalized_at  TIMESTAMPTZ,
    CHECK ((status = 'final') = (finalized_at IS NOT NULL))
);
CREATE INDEX idx_reports_task ON reports (task_id, id DESC);

-- Only task status and short non-sensitive summaries are ever queued here.
CREATE TABLE notifications (
    id              BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    kind            TEXT NOT NULL,
    task_id         BIGINT,
    text            TEXT NOT NULL CHECK (length(text) BETWEEN 1 AND 1000),
    state           TEXT NOT NULL DEFAULT 'pending'
                        CHECK (state IN ('pending', 'sending', 'sent', 'failed', 'skipped')),
    attempts        INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_error      TEXT NOT NULL DEFAULT '',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    sent_at         TIMESTAMPTZ
);
CREATE INDEX idx_notifications_due ON notifications (next_attempt_at) WHERE state IN ('pending', 'sending');
